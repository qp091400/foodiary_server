"""Write app/services/food_words.txt: common ingredient words from the recipe database, used by name_fix to correct OCR typos.

Usage: python -m scripts.build_food_words [path/to/recipes.sqlite3]
Only Hangul words of 3+ letters used by at least MIN_RECIPES recipes, minus cooking phrases and misspellings.
"""

import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "app" / "services" / "food_words.txt"
MIN_RECIPES = 300  # TODO: balance. Rarer keys are mostly cooking phrases ("송송썰은파")
# Phrases and misspellings that are not product words. A misspelling here would "fix" correct names into it.
EXCLUDED = {
    "다진파", "뜨거운물", "따뜻한물", "불린쌀", "갈은깨", "공기밥", "쌀뜨물", "노른자", "김칫국물", "매운고추", "붉은고추",
    "청양초", "청량고추", "식용류", "찹쌀풀", "파뿌리", "어린잎채소", "새싹채소", "샐러드채소", "미니단호박", "천연조미료",
}


def main() -> None:
    database = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "recipe_data" / "image-seed" / "recipes.sqlite3"
    with sqlite3.connect(f"file:{database}?mode=ro", uri=True) as connection:
        rows = connection.execute(
            "SELECT key FROM ingredients GROUP BY key HAVING COUNT(*) >= ? ORDER BY key", (MIN_RECIPES,)
        ).fetchall()
    words = [key for (key,) in rows if re.fullmatch(r"[가-힣]{3,}", key) and key not in EXCLUDED]
    header = f"# Generated by scripts/build_food_words.py (recipe keys used by >= {MIN_RECIPES} recipes). Do not edit by hand.\n"
    OUTPUT.write_text(header + "\n".join(words) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(words)} words -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
